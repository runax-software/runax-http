using System.Text;

namespace Runax.Http.SourceGenerator;

/// <summary>
/// Writes the implementation for one client interface.
/// </summary>
/// <remarks>
/// The emitted methods are deliberately thin — build a <c>ClientRequest</c>, hand it to the
/// executor. Everything that could be decided once lives in the runtime instead, because logic
/// here is logic you debug by reading generated output and fix by shipping a new compiler package
/// to everybody.
/// </remarks>
internal static class Emitter
{
    private const string Runtime = "global::Runax.Http";

    internal static string Emit(ClientModel client)
    {
        var code = new StringBuilder();

        code.AppendLine("// <auto-generated/>");
        code.AppendLine("#nullable enable");
        code.AppendLine();

        var indent = string.Empty;

        if (client.NamespaceName is not null)
        {
            code.AppendLine($"namespace {client.NamespaceName}");
            code.AppendLine("{");
            indent = "    ";
        }

        EmitClass(code, client, indent);
        code.AppendLine();
        EmitRegistration(code, client, indent);

        if (client.NamespaceName is not null)
            code.AppendLine("}");

        return code.ToString();
    }

    private static void EmitClass(StringBuilder code, ClientModel client, string indent)
    {
        code.AppendLine($"{indent}/// <summary>");
        code.AppendLine($"{indent}/// Generated implementation of <see cref=\"{EscapeXml(client.QualifiedContractName)}\"/>.");
        code.AppendLine($"{indent}/// </summary>");
        code.AppendLine($"{indent}[global::System.CodeDom.Compiler.GeneratedCode(\"Runax.Http\", null)]");
        code.AppendLine($"{indent}internal sealed partial class {client.ImplementationName} : {client.QualifiedContractName}");
        code.AppendLine($"{indent}{{");
        code.AppendLine($"{indent}    private readonly {Runtime}.IHttpContractExecutor _executor;");
        code.AppendLine();
        code.AppendLine($"{indent}    public {client.ImplementationName}({Runtime}.IHttpContractExecutor executor)");
        code.AppendLine($"{indent}    {{");
        code.AppendLine($"{indent}        _executor = executor ?? throw new global::System.ArgumentNullException(nameof(executor));");
        code.AppendLine($"{indent}    }}");

        foreach (var method in client.Methods)
        {
            code.AppendLine();
            EmitMethod(code, method, indent + "    ");
        }

        code.AppendLine($"{indent}}}");
    }

    private static void EmitMethod(StringBuilder code, MethodModel method, string indent)
    {
        var signature = string.Join(
            ", ",
            method.Parameters.Select(parameter => $"{parameter.TypeName} {parameter.Name}"));

        code.AppendLine($"{indent}/// <inheritdoc />");
        code.AppendLine($"{indent}public async {method.ReturnTypeName} {method.Name}({signature})");
        code.AppendLine($"{indent}{{");

        var cancellation = method.Parameters
            .FirstOrDefault(parameter => parameter.Binding == ParameterBinding.CancellationToken);

        var token = cancellation?.Name ?? "default";

        EmitRequest(code, method, indent + "    ");
        code.AppendLine();
        EmitDispatch(code, method, token, indent + "    ");

        code.AppendLine($"{indent}}}");
    }

    private static void EmitRequest(StringBuilder code, MethodModel method, string indent)
    {
        code.AppendLine($"{indent}var __request = new {Runtime}.Requests.ClientRequest");
        code.AppendLine($"{indent}{{");
        code.AppendLine($"{indent}    Method = {Runtime}.RequestMethod.{method.RequestMethod},");
        code.AppendLine($"{indent}    Template = {Literal(method.Template)},");

        EmitPairs(
            code,
            indent,
            "PathValues",
            "string, object?",
            method.Parameters
                .Where(parameter => parameter.Binding == ParameterBinding.Path)
                .Select(parameter => (Literal(parameter.WireName), parameter.Name)));

        EmitPairs(
            code,
            indent,
            "QueryValues",
            "string, object?",
            method.Parameters
                .Where(parameter => parameter.Binding == ParameterBinding.Query)
                .Select(parameter => (Literal(parameter.WireName), parameter.Name)));

        var headers = method.ConstantHeaders
            .Select(header => (Literal(header.Key), Literal(header.Value)))
            .Concat(method.Parameters
                .Where(parameter => parameter.Binding == ParameterBinding.Header)
                .Select(parameter => (Literal(parameter.WireName), ToHeaderValue(parameter))))
            .ToList();

        EmitPairs(code, indent, "Headers", "string, string?", headers);

        var body = method.Parameters
            .FirstOrDefault(parameter => parameter.Binding == ParameterBinding.Body);

        if (body is not null)
            EmitBody(code, indent, method, body);

        if (method.TransportName is not null)
            code.AppendLine($"{indent}    TransportName = {Literal(method.TransportName)},");

        code.AppendLine($"{indent}}};");
    }

    private static void EmitBody(StringBuilder code, string indent, MethodModel method, ParameterModel body)
    {
        if (method.BodyFormat == "Raw")
        {
            // Already in wire form. A string becomes UTF-8 bytes; a stream stays a stream, so a
            // large upload is not buffered on the way through.
            code.AppendLine($"{indent}    Content = {Runtime}.Requests.RawBody.Create({body.Name}),");

            return;
        }

        // The serializer is called with the parameter's static type, so nothing has to reflect over
        // the body to discover what is being sent.
        code.AppendLine($"{indent}    Content = _executor.Serializer.Serialize<{body.TypeName}>({body.Name}),");
    }

    private static void EmitDispatch(StringBuilder code, MethodModel method, string token, string indent)
    {
        if (method.Shape == ResultShape.ApiResult)
        {
            EmitResultDispatch(code, method, token, indent);
            return;
        }

        switch (method.Shape)
        {
            case ResultShape.Empty:
                code.AppendLine($"{indent}await _executor.SendAsync(__request, {token}).ConfigureAwait(false);");
                break;

            case ResultShape.ApiResponse:
                code.AppendLine($"{indent}return await _executor.SendForApiResponseAsync(__request, {token}).ConfigureAwait(false);");
                break;

            case ResultShape.ApiResponseOfContent:
                code.AppendLine($"{indent}return await _executor.SendForApiResponseAsync<{method.ContentTypeName}>(__request, {token}).ConfigureAwait(false);");
                break;

            default:
                code.AppendLine($"{indent}return (await _executor.SendAsync<{method.ContentTypeName}>(__request, {token}).ConfigureAwait(false))!;");
                break;
        }
    }

    /// <summary>
    /// Reads the whole response, then walks the declared responses in source order and
    /// deserializes the first whose conditions hold.
    /// </summary>
    /// <remarks>
    /// Each branch names a concrete type, so choosing at run time costs nothing in reflection —
    /// the decision is dynamic, the deserialization is not.
    /// </remarks>
    private static void EmitResultDispatch(
        StringBuilder code,
        MethodModel method,
        string token,
        string indent)
    {
        code.AppendLine($"{indent}var __envelope = await _executor.SendForEnvelopeAsync(__request, {token}).ConfigureAwait(false);");

        var hasFallback = false;

        foreach (var response in method.Responses)
        {
            code.AppendLine();

            if (response.IsUnconditional)
            {
                hasFallback = true;
                code.AppendLine($"{indent}return await _executor.ToResultAsync<{response.TypeName}>(__envelope, {token}).ConfigureAwait(false);");

                break;
            }

            code.AppendLine($"{indent}if ({BuildCondition(response)})");
            code.AppendLine($"{indent}    return await _executor.ToResultAsync<{response.TypeName}>(__envelope, {token}).ConfigureAwait(false);");
        }

        if (hasFallback)
            return;

        code.AppendLine();
        code.AppendLine($"{indent}// Nothing declared matched. The body is kept on the result so the caller can see");
        code.AppendLine($"{indent}// what arrived instead, which is the only clue as to what [Response] is missing.");
        code.AppendLine($"{indent}return _executor.Unmatched(__envelope);");
    }

    /// <summary>
    /// Builds the condition for one declared response. Several conditions on one attribute are
    /// combined with AND: they describe one response, not alternatives.
    /// </summary>
    private static string BuildCondition(ResponseModel response)
    {
        var tests = new List<string>();

        if (response.StatusCode is { } status)
            tests.Add($"__envelope.HasStatus({status})");

        if (response.MinStatusCode is not null || response.MaxStatusCode is not null)
        {
            var low = response.MinStatusCode ?? 0;
            var high = response.MaxStatusCode ?? 999;

            tests.Add($"__envelope.HasStatusInRange({low}, {high})");
        }

        if (response.JsonProperty is { } property)
        {
            tests.Add(response.JsonPropertyEquals is { } expected
                ? $"__envelope.JsonPropertyEquals({Literal(property)}, {Literal(expected)})"
                : $"__envelope.HasJsonProperty({Literal(property)})");
        }

        if (response.Header is { } header)
        {
            tests.Add(response.HeaderEquals is { } headerValue
                ? $"__envelope.HeaderEquals({Literal(header)}, {Literal(headerValue)})"
                : $"__envelope.HasHeader({Literal(header)})");
        }

        return string.Join(" && ", tests);
    }

    private static void EmitPairs(
        StringBuilder code,
        string indent,
        string property,
        string pairTypes,
        IEnumerable<(string Key, string Value)> pairs)
    {
        var materialized = pairs.ToList();
        if (materialized.Count == 0)
            return;

        code.AppendLine($"{indent}    {property} = new global::System.Collections.Generic.KeyValuePair<{pairTypes}>[]");
        code.AppendLine($"{indent}    {{");

        foreach (var (key, value) in materialized)
            code.AppendLine($"{indent}        new global::System.Collections.Generic.KeyValuePair<{pairTypes}>({key}, {value}),");

        code.AppendLine($"{indent}    }},");
    }

    private static void EmitRegistration(StringBuilder code, ClientModel client, string indent)
    {
        code.AppendLine($"{indent}/// <summary>");
        code.AppendLine($"{indent}/// Registers <see cref=\"{client.ImplementationName}\"/> so that");
        code.AppendLine($"{indent}/// <c>AddRunaxClient&lt;{EscapeXml(client.ContractName)}&gt;()</c> can find it without reflection.");
        code.AppendLine($"{indent}/// </summary>");
        code.AppendLine($"{indent}[global::System.CodeDom.Compiler.GeneratedCode(\"Runax.Http\", null)]");
        code.AppendLine($"{indent}internal static class {client.ImplementationName}Registration");
        code.AppendLine($"{indent}{{");
        code.AppendLine($"{indent}    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        code.AppendLine($"{indent}    internal static void Register()");
        code.AppendLine($"{indent}    {{");
        code.AppendLine($"{indent}        {Runtime}.DependencyInjection.GeneratedClientRegistry.Register(");
        code.AppendLine($"{indent}            new {Runtime}.DependencyInjection.GeneratedClient");
        code.AppendLine($"{indent}            {{");
        code.AppendLine($"{indent}                Contract = typeof({client.QualifiedContractName}),");
        code.AppendLine($"{indent}                Factory = static __executor => new {client.ImplementationName}(__executor),");

        if (client.BaseAddress is not null)
            code.AppendLine($"{indent}                BaseAddress = {Literal(client.BaseAddress)},");

        if (client.TransportName is not null)
            code.AppendLine($"{indent}                TransportName = {Literal(client.TransportName)},");

        if (client.DeclaredTransportNames.Length > 0)
        {
            code.AppendLine($"{indent}                DeclaredTransportNames = new string[]");
            code.AppendLine($"{indent}                {{");

            foreach (var name in client.DeclaredTransportNames)
                code.AppendLine($"{indent}                    {Literal(name)},");

            code.AppendLine($"{indent}                }},");
        }

        if (client.DefaultHeaders.Length > 0)
        {
            code.AppendLine($"{indent}                DefaultHeaders = new global::System.Collections.Generic.KeyValuePair<string, string>[]");
            code.AppendLine($"{indent}                {{");

            foreach (var header in client.DefaultHeaders)
            {
                code.AppendLine(
                    $"{indent}                    new global::System.Collections.Generic.KeyValuePair<string, string>("
                    + $"{Literal(header.Key)}, {Literal(header.Value)}),");
            }

            code.AppendLine($"{indent}                }},");
        }

        code.AppendLine($"{indent}            }});");
        code.AppendLine($"{indent}    }}");
        code.AppendLine($"{indent}}}");
    }

    /// <summary>
    /// A header parameter's value, as a string. Formatting matches query and path values so the
    /// same argument spells the same thing wherever it is bound.
    /// </summary>
    private static string ToHeaderValue(ParameterModel parameter)
        => parameter.TypeName == "string" || parameter.TypeName == "string?"
            ? parameter.Name
            : $"{Runtime}.Requests.HeaderValue.Format({parameter.Name})";

    private static string Literal(string value)
    {
        var escaped = value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n");

        return $"\"{escaped}\"";
    }

    private static string EscapeXml(string value)
        => value.Replace("&", "&amp;").Replace("<", "{").Replace(">", "}");
}
